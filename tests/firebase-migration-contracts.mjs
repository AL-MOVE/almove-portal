import assert from 'node:assert/strict';
import fs from 'node:fs';

const proxy = fs.readFileSync(new URL('../api/almove.js', import.meta.url), 'utf8');
const firebase = fs.readFileSync(new URL('../api/_firebase.js', import.meta.url), 'utf8');
const invite = fs.readFileSync(new URL('../api/invite.js', import.meta.url), 'utf8');
const appsScript = fs.readFileSync(new URL('../apps-script/Code.js', import.meta.url), 'utf8');
const browserAdapter = fs.readFileSync(new URL('../js/firebase-auth.js', import.meta.url), 'utf8');
const browserConfig = fs.readFileSync(new URL('../js/firebase-config.js', import.meta.url), 'utf8');
const browserSdk = fs.readFileSync(new URL('../js/firebase-sdk.js', import.meta.url), 'utf8');
const developmentMigration = fs.readFileSync(new URL('../api/dev-crm-migration.js', import.meta.url), 'utf8');
const developmentMigrationPage = fs.readFileSync(new URL('../dev-migration.html', import.meta.url), 'utf8');

assert.match(proxy, /obterAssertacaoFirebasePortal/);
assert.match(firebase, /verifyIdToken\(correspondencia\[1\], true\)/, 'A Vercel tem de verificar tokens revogados.');
assert.match(firebase, /token\.email_verified/, 'O email Firebase tem de ser confirmado.');
assert.match(firebase, /PORTAL_APPS_SCRIPT_HMAC_SECRET/, 'A identidade enviada ao Apps Script tem de ser assinada.');
assert.match(invite, /timingSafeEqual/, 'O convite CRM deve validar a assinatura em tempo constante.');
assert.match(invite, /generatePasswordResetLink/, 'O convite deve gerar um link único para definir palavra-passe.');
assert.match(invite, /auth\.listUsers\(1\)/, 'O diagnóstico assinado deve confirmar a credencial Firebase sem criar contas.');
assert.match(appsScript, /obterClientePorAssertacaoFirebasePortal_/);
assert.match(appsScript, /pedirLinkConviteFirebasePortal_/, 'O CRM deve pedir links de convite ao servidor Firebase.');
assert.match(appsScript, /diagnosticarConviteFirebasePortal_/, 'O Apps Script deve conseguir diagnosticar a ligação de convite.');
assert.match(appsScript, /obterClientePorEmailPortal_\(email\)/, 'O email Firebase deve corresponder a um único cliente CRM.');
assert.match(appsScript, /firebase:/, 'A assertação não pode ser confundida com o token legado.');
assert.match(browserAdapter, /browserLocalPersistence/, 'A sessão Firebase deve sobreviver ao fecho normal da PWA.');
assert.match(browserAdapter, /sendPasswordResetEmail/, 'A recuperação de palavra-passe tem de estar disponível.');
assert.match(browserAdapter, /sendEmailVerification/, 'A confirmação do email tem de poder ser reenviada.');
const devCrm = fs.readFileSync(new URL('../dev-crm.html', import.meta.url), 'utf8');
assert.match(devCrm, /reenviarConfirmacao/, 'O verificador CRM deve permitir confirmar contas de desenvolvimento.');
assert.match(browserSdk, /ALMOVE_FIREBASE_SDK/, 'O SDK Firebase deve ser servido localmente pelo portal.');
assert.doesNotMatch(browserAdapter, /www\.gstatic\.com/, 'O adaptador não deve depender de imports externos no browser.');
assert.match(browserConfig, /projectId: 'almove-portal'/, 'O portal real deve manter a configuração Firebase de produção.');
assert.match(browserConfig, /\/api\/firebase-config/, 'Uma pré-visualização tem de pedir a configuração Firebase própria à Vercel.');
assert.match(browserConfig, /location\.hostname === 'portal\.almove\.pt'/, 'A pré-visualização não pode reutilizar a configuração Firebase de produção.');
assert.match(browserConfig, /CONFIGURACAO_FIREBASE_EM_FALTA/, 'Sem configuração própria, a pré-visualização deve falhar fechada.');
assert.doesNotMatch(browserConfig, /measurementId|getAnalytics/, 'O portal não deve carregar Analytics para autenticação.');
assert.match(developmentMigration, /crmMigrationNotes/, 'A cópia Development deve incluir notas privadas do CRM.');
assert.match(developmentMigration, /crmMigrationTrainingPlans/, 'A cópia Development deve incluir planos de treino.');
assert.match(appsScript, /notas: contarLinhasComCampos\('DB_NOTAS_CRM'/, 'A verificação deve contar notas na origem.');
assert.match(appsScript, /planos: contarLinhasComCampos\('DB_PLANOS_TREINO'/, 'A verificação deve contar planos na origem.');
assert.match(developmentMigrationPage, /Atualizar cópia Development/, 'A página deve permitir atualizar uma cópia já em paridade.');
console.log('Contratos de migração Firebase validados.');
